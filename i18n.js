  const LANGS = [
    { code: 'en', short: 'EN', name: 'English', html: 'en', locale: 'en-GB' },
    { code: 'si', short: 'සිං', name: 'සිංහල', html: 'si', locale: 'si-LK' },
    { code: 'ta', short: 'தமி', name: 'தமிழ்', html: 'ta', locale: 'ta-LK' },
    { code: 'zh', short: '中文', name: '中文', html: 'zh-Hans', locale: 'zh-CN' },
    { code: 'ja', short: '日本', name: '日本語', html: 'ja', locale: 'ja-JP' },
  ];
  const byCode = Object.fromEntries(LANGS.map((l) => [l.code, l]));
  const KEY = 'lp-lang';

  const pick = () => {
    const q = new URLSearchParams(location.search).get('lang');
    if (q && byCode[q]) return q;
    try { const s = localStorage.getItem(KEY); if (s && byCode[s]) return s; } catch (e) {}
    return 'en';
  };
  let lang = pick();

  const fill = (str, vars) => str.replace(/\{(\w+)\}/g, (_, k) => (vars && k in vars ? vars[k] : ''));
  const LP = {
    get lang() { return lang; },
    get locale() { return byCode[lang].locale; },
    t(key, vars) { const d = DYNAMIC[lang] || DYNAMIC.en; return fill(d[key] ?? DYNAMIC.en[key] ?? key, vars); },
    s(key) { const e = STATIC[key]; return e ? (e[lang] ?? e.en) : key; },
    set: (code) => apply(code),
  };
  window.LP = LP;

  const apply = (code) => {
    if (!byCode[code]) return;
    lang = code;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const e = STATIC[el.dataset.i18n];
      if (e) el.innerHTML = e[lang] ?? e.en;
    });
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      const e = ATTRS[el.dataset.i18nPh];
      if (e) el.placeholder = e[lang] ?? e.en;
    });
    const y = document.getElementById('year');
    if (y) y.textContent = new Date().getFullYear();
    document.documentElement.lang = byCode[lang].html;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    if (btnLabel) btnLabel.textContent = byCode[lang].short;
    menu && menu.querySelectorAll('[role="option"]').forEach((o) => o.setAttribute('aria-selected', String(o.dataset.lang === lang)));
    if (btn) btn.setAttribute('aria-label', `${LP.t('lang_label')}: ${byCode[lang].name}`);
    document.dispatchEvent(new CustomEvent('lp:lang', { detail: { lang } }));
  };

  // ---- Language switcher in the top menu ----
  let btn, btnLabel, menu;
  const nav = document.querySelector('.nav__inner');
  if (nav) {
    const wrap = document.createElement('div');
    wrap.className = 'lang';
    wrap.innerHTML = `
      <button class="lang__btn" type="button" aria-haspopup="listbox" aria-expanded="false">
        <svg viewBox="0 0 24 24" width="16" height="16" aria-hidden="true"><circle cx="12" cy="12" r="9" fill="none" stroke="currentColor" stroke-width="1.6"/><path d="M3 12h18M12 3c2.8 3 2.8 15 0 18M12 3c-2.8 3-2.8 15 0 18" fill="none" stroke="currentColor" stroke-width="1.6"/></svg>
        <span class="lang__code"></span>
      </button>
      <ul class="lang__menu" role="listbox" hidden>
        ${LANGS.map((l) => `<li role="option" data-lang="${l.code}" lang="${l.html}" tabindex="-1">${l.name}</li>`).join('')}
      </ul>`;
    const anchor = nav.querySelector('.nav__wa') || nav.querySelector('.nav__call');
    nav.insertBefore(wrap, anchor);
    btn = wrap.querySelector('.lang__btn');
    btnLabel = wrap.querySelector('.lang__code');
    menu = wrap.querySelector('.lang__menu');
    const open = (yes) => {
      menu.hidden = !yes;
      btn.setAttribute('aria-expanded', String(yes));
      if (yes) (menu.querySelector('[aria-selected="true"]') || menu.firstElementChild).focus();
    };
    btn.addEventListener('click', (e) => { e.stopPropagation(); open(menu.hidden); });
    menu.addEventListener('click', (e) => {
      const o = e.target.closest('[role="option"]');
      if (!o) return;
      apply(o.dataset.lang);
      open(false);
      btn.focus();
    });
    menu.addEventListener('keydown', (e) => {
      const items = [...menu.children];
      const i = items.indexOf(document.activeElement);
      if (e.key === 'ArrowDown') { e.preventDefault(); items[(i + 1) % items.length].focus(); }
      if (e.key === 'ArrowUp') { e.preventDefault(); items[(i - 1 + items.length) % items.length].focus(); }
      if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); document.activeElement.click(); }
      if (e.key === 'Escape') { open(false); btn.focus(); }
    });
    document.addEventListener('click', (e) => { if (!wrap.contains(e.target)) open(false); });
  }

  apply(lang);
